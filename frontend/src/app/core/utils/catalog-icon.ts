function catalogSlug(value: string | null | undefined): string {
  return (value ?? '')
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

export function majorIconUrl(slug: string | null | undefined): string {
  return `assets/icons/majors/${MAJOR_ICONS.get(catalogSlug(slug)) ?? 'default'}.${ICON_EXTENSION}`;
}

export function subjectIconName(slug: string | null | undefined): string {
  return SUBJECT_ICONS.get(catalogSlug(slug)) ?? 'menu_book';
}

/** Legacy image helper. Subject cards now use subjectIconName; only a default image is shipped. */
export function subjectIconUrl(_slug: string | null | undefined): string {
  return fallbackIconUrl('subjects');
}

export function fallbackIconUrl(kind: 'majors' | 'subjects'): string {
  return `assets/icons/${kind}/default.${ICON_EXTENSION}`;
}

/** Swap in the default icon once; the endsWith check prevents an infinite error loop. */
export function handleIconError(event: Event, kind: 'majors' | 'subjects'): void {
  const img = event.target as HTMLImageElement;
  const fallback = fallbackIconUrl(kind);
  if (!img.src.endsWith(fallback)) {
    img.src = fallback;
  }
}
